export const ARTICLE_SLUGS = ARTICLES.map((a) => a.slug)

export function getArticle(slug: string) {
  return ARTICLES.find((a) => a.slug === slug) ?? null
}

/**
 * Время чтения считается из самого текста, а не проставляется руками:
 * иначе после первой же правки цифра начинает врать. 160 слов в минуту —
 * средний темп чтения на русском.
 */
export function readMinutes(a: Article) {
  const words = a.blocks
    .flatMap((b) => {
      if (b.t === 'list') return b.items
      if (b.t === 'table') return [...b.head, ...b.rows.flat()]
      if (b.t === 'figure') return []
      return [b.text]
    })
    .join(' ')
    .split(/\s+/)
    .filter((w) => /[а-яёa-z]/i.test(w)).length

  return Math.max(1, Math.round(words / 160))
}
