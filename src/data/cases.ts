/**
 * Страницы работ: /raboty/<slug>/.
 *
 * Что здесь можно писать, а что нельзя. Почти все работы — демо-концепты,
 * а не клиентские заказы, и у них нет ни заказчика, ни запуска, ни статистики.
 * Значит, кейса в привычном смысле — «было столько заявок, стало вдвое больше» —
 * написать не из чего, и придумывать такие цифры нельзя ни при каких условиях.
 *
 * Поэтому разбор здесь про решения, а не про результат: какой человек приходит
 * на страницу, чего он боится, в каком порядке ему отвечают и почему именно так.
 * Это то, что действительно есть, и одновременно то, что ищет человек, который
 * выбирает подрядчика, — ему нужно понять, как я думаю, а не поверить в цифру.
 *
 * Блок «чего здесь нет» такой же содержательный, как «решения»: половина
 * отличий этих страниц от шаблона — в том, чего на них не поставили.
 */

export type CasePage = {
  /** Адрес: /raboty/<slug>/. */
  slug: string
  /** id из projects.ts — оттуда берутся постер, видео, ниша, город и ссылка. */
  projectId: string
  h1: string
  lead: string
  /** <title>, до 60 символов. */
  title: string
  /** <meta description>, 140–160 символов. */
  description: string
  /** Кто приходит на страницу и чего боится. Два-три абзаца. */
  task: string[]
  /** Что решено и почему. Ядро страницы. */
  decisions: { n: string; why: string }[]
  /** Чего на странице нет намеренно. */
  omitted: { n: string; why: string }[]
  /**
   * Чего не хватает, чтобы работа стала живым сайтом.
   *
   * Есть только там, где страница собрана под конкретный названный бизнес,
   * который её ещё не купил: у демо-концепта без адресата такого списка
   * быть не может, а у клиентского сайта он уже закрыт. Секция не рендерится,
   * если поля нет.
   */
  launch?: { n: string; why: string }[]
}

