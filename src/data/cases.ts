export const CASE_SLUGS = CASES.map((c) => c.slug)

export function getCase(slug: string) {
  return CASES.find((c) => c.slug === slug) ?? null
}

/** Работа, к которой относится разбор. Без неё страницы быть не может. */
export function projectOf(c: CasePage) {
  const p = PROJECTS.find((x) => x.id === c.projectId)
  if (!p) throw new Error(`cases.ts: нет работы с id ${c.projectId}`)
  return p
}

/** Адрес разбора по id работы — для карточек в витрине и на нишевых страницах. */
export function caseHrefFor(projectId: string) {
  const c = CASES.find((x) => x.projectId === projectId)
  return c ? `/raboty/${c.slug}/` : null
}
