/**
 * Городские посадочные страницы.
 *
 * Главная закреплена за Нижнекамском — это домашний город, и дублировать его
 * отдельной страницей значит столкнуть две своих же страницы по одному запросу.
 * Остальные города живут на /<slug>/.
 *
 * Тексты у каждого города свои. Это принципиально: на первом экране сайта
 * написано «ни одного шаблона с автозаменой города», и страница, собранная
 * автозаменой, опровергала бы этот тезис быстрее любого конкурента.
 * Поэтому здесь нет общего шаблона с подстановкой — у каждого города свой
 * повод, своя причина выбрать подрядчика из соседнего города и своя правда
 * про конкуренцию в выдаче.
 */

export type City = {
  slug: string
  /** Именительный: «Казань». */
  name: string
  /** Предложный с предлогом: «в Казани». Идёт в заголовки. */
  inCity: string
  /** Родительный: «Казани». Идёт в «бизнеса Казани». */
  ofCity: string
  /** Расстояние от Нижнекамска — реальное, по трассе. */
  distanceKm: number
  /** Сколько ехать на машине. Проверяемо, поэтому можно называть. */
  driveTime: string
  /** H1 страницы. */
  h1: string
  /** Подзаголовок под H1. */
  lead: string
  /** Одна строка для карточки в блоке «География» на главной. */
  cardLine: string
  /** <title>. До 60 символов, ключ в начале. */
  title: string
  /** <meta description>. 140–160 символов. */
  description: string
  /** Три абзаца по существу: чем этот рынок отличается. Без воды. */
  intro: string[]
  /** Блок «почему подрядчик не из вашего города» — свой аргумент на каждый. */
  proximity: { head: string; body: string }
  /** id работ из projects.ts, которые уместно показать первыми. */
  featured: string[]
  /** Районы и посёлки — для длинного хвоста и естественности текста. */
  areas: string[]
}

