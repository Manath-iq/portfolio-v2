/**
 * Числительные словами.
 *
 * Количество работ попадает прямо в текст на семи страницах: «Десять сайтов.
 * У каждого — разбор». Цифрой такую строку писать нельзя — она читается как
 * таблица, а не как речь. Хардкодить слово тоже нельзя: оно разъезжается
 * с данными на первой же добавленной работе, и сайт начинает врать про
 * самого себя в первой же строке первого экрана.
 *
 * Таблица начинается с пяти: с этого места числительное не зависит от рода,
 * и одно слово подходит и к «сайтам», и к «работам». Ниже пяти форма разная
 * («один сайт», но «одна работа»), и понадобится это тогда, когда работ
 * станет меньше пяти, то есть никогда.
 */
const NOMINATIVE: Record<number, string> = {
  5: 'пять',
  6: 'шесть',
  7: 'семь',
  8: 'восемь',
  9: 'девять',
  10: 'десять',
  11: 'одиннадцать',
  12: 'двенадцать',
  13: 'тринадцать',
  14: 'четырнадцать',
  15: 'пятнадцать',
  16: 'шестнадцать',
  17: 'семнадцать',
  18: 'восемнадцать',
  19: 'девятнадцать',
  20: 'двадцать',
}

/** Родительный падеж — для оборота «десять из одиннадцати». «Восьми» неправильное. */
const GENITIVE: Record<number, string> = {
  5: 'пяти',
  6: 'шести',
  7: 'семи',
  8: 'восьми',
  9: 'девяти',
  10: 'десяти',
  11: 'одиннадцати',
  12: 'двенадцати',
  13: 'тринадцати',
  14: 'четырнадцати',
  15: 'пятнадцати',
  16: 'шестнадцати',
  17: 'семнадцати',
  18: 'восемнадцати',
  19: 'девятнадцати',
  20: 'двадцати',
}

/** Вне таблицы отдаём цифру: испорченная строка хуже, чем менее красивая. */
export function numeral(n: number) {
  return NOMINATIVE[n] ?? String(n)
}

export function numeralOf(n: number) {
  return GENITIVE[n] ?? String(n)
}

/** Начало предложения: «Одиннадцать сайтов. У каждого — разбор». */
export function cap(s: string) {
  return s.charAt(0).toUpperCase() + s.slice(1)
}
